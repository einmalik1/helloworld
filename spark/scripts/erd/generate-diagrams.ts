function mermaidHeader(title: string): string {
  return [
    `%% ${title}`,
    "%% Generated by spark/scripts/erd/generate-diagrams.ts — do not edit by hand.",
    "%% Source: spec/erd/schema.sql (single source of truth)",
    "erDiagram",
  ].join("\n");
}

function nodeLabel(table: Table): string {
  const label = `${table.label} · ${table.columns.length} fields`.replace(/"/g, "'");
  return `${table.name}["${label}"]`;
}

// Audit-Kanten (created_by/updated_by/… → user) sind auf ~27 der 59 Kanten
// reine Buchhaltung. Sie alle in `user` münden zu lassen, macht jedes
// Übersichts-Diagramm unlesbar — sie gehören nur ins Entity-Detail.
const AUDIT_FK_COLUMNS = new Set([
  "created_by",
  "updated_by",
  "granted_by",
  "revoked_by",
  "changed_by",
  "actor_id",
]);

function isAuditEdge(edge: { fromColumn: string }): boolean {
  return AUDIT_FK_COLUMNS.has(edge.fromColumn);
}

// Mermaid erDiagram liest `A ||--o{ B` als "ein A, viele B". Eine FK-Spalte
// opportunity.owner_id → user.id bedeutet aber: viele Opportunities zeigen auf
// EINEN User — die Kante muss vom Parent zur Child-Tabelle laufen, also
// user ||--o{ opportunity. Die Diagramm-Kanten laufen deshalb entgegen der
// FK-Richtung: fromTable = referenzierte Tabelle, toTable = FK-Halter.
// Logische Referenzen (04 §5, 06 §6 — bewusst kein FK) laufen als `..` statt
// `--`: die offizielle erDiagram-Syntax fuer nicht-identifizierende
// Beziehungen, gerendert als gestrichelte Linie.
function diagramEdge(fromTable: string, toTable: string, label: string, dashed = false): string {
  const line = dashed ? ".." : "--";
  return `  ${fromTable} ||${line}o{ ${toTable} : "${label}"`;
}

function bigPictureMmd(): string {
  const lines = [mermaidHeader("Big Picture — all tables, business FK edges")];
  lines.push("  direction LR");
  for (const table of model.tables) {
    lines.push(`  ${nodeLabel(table)}`);
  }
  for (const edge of model.edges) {
    if (isAuditEdge(edge)) continue;
    lines.push(diagramEdge(edge.toTable, edge.fromTable, edge.fromColumn, edge.kind === "logical"));
  }
  return `${lines.join("\n")}\n`;
}

function categoryMmd(catKey: string): string {
  const category = model.categories.find((c) => c.key === catKey);
  if (!category) return "";
  const members = new Set(category.tables);
  const lines = [mermaidHeader(`Category: ${category.label} (${category.tables.length} tables)`)];
  lines.push("  direction LR");
  for (const tableName of category.tables) {
    const table = tablesByName.get(tableName);
    if (table) lines.push(`  ${nodeLabel(table)}`);
  }
  // erDiagram erlaubt keine %%-Kommentare am Zeilenende — Cross-Category
  // wird im Kanten-Label markiert.
  for (const edge of model.edges) {
    const fromInside = members.has(edge.fromTable);
    const toInside = members.has(edge.toTable);
    if (!fromInside && !toInside) continue;
    if (isAuditEdge(edge)) continue;
    const label = fromInside && toInside ? edge.fromColumn : `${edge.fromColumn} (cross)`;
    lines.push(diagramEdge(edge.toTable, edge.fromTable, label, edge.kind === "logical"));
  }
  return `${lines.join("\n")}\n`;
}

function entityMmd(name: string): string {
  const table = tablesByName.get(name);
  if (!table) return "";
  const label = table.label.replace(/"/g, "'");
  const lines = [mermaidHeader(`Entity: ${table.name} (${table.label})`)];
  lines.push(`  ${table.name}["${label}"] {`);
  for (const column of table.columns) {
    // Mermaid erDiagram-Attributtypen dürfen nur Wortzeichen enthalten —
    // Klammern und Klartext-Suffixe wie "(18)" brechen den Parser.
    const type = column.sqlType
      .toUpperCase()
      .replace(/[^A-Z0-9_]/g, "_")
      .replace(/_+/g, "_");
    const pk = column.isPrimaryKey ? " PK" : "";
    const fk = column.references ? " FK" : "";
    lines.push(`    ${type} ${column.name}${pk}${fk}`);
  }
  lines.push("  }");
  // Nachbar-Kanten: alles was auf diese Tabelle zeigt oder von ihr ausgeht.
  // Hier inklusive Audit-Kanten (im Entity-Detail ist jede Kante relevant).
  // Nicht deklarierte Gegenstellen rendert Mermaid automatisch als leere Box.
  for (const edge of model.edges) {
    if (edge.fromTable === table.name || edge.toTable === table.name) {
      lines.push(
        diagramEdge(edge.toTable, edge.fromTable, edge.fromColumn, edge.kind === "logical"),
      );
    }
  }
  return `${lines.join("\n")}\n`;
}

