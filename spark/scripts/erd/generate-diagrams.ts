function xmlEscape(text: string): string {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function drawioWrap(diagramName: string, nodesXml: string, edgesXml: string): string {
  return `<?xml version="1.0" encoding="UTF-8"?>
<mxfile host="app.diagrams.net" modified="${new Date().toISOString()}" agent="erd-pipeline" version="24.0.0">
  <diagram id="${diagramName}" name="${diagramName}">
    <mxGraphModel dx="1400" dy="900" grid="1" gridSize="10" guides="1" tooltips="1" connect="1" arrows="1" fold="1" page="1" pageScale="1" pageWidth="1600" pageHeight="1200" math="0" shadow="0">
      <root>
        <mxCell id="0"/>
        <mxCell id="1" parent="0"/>
${nodesXml}
${edgesXml}
      </root>
    </mxGraphModel>
  </diagram>
</mxfile>
`;
}

function mxCellNode(
  id: string,
  htmlLabel: string,
  x: number,
  y: number,
  width: number,
  height: number,
  fill: string,
  fontColor: string,
  dashed = false,
): string {
  const style = `rounded=1;whiteSpace=wrap;html=1;fillColor=${fill};fontColor=${fontColor};${
    dashed ? "dashed=1;" : ""
  }strokeColor=${dashed ? "#94a3b8" : "none"}`;
  return `        <mxCell id="${id}" value="${xmlEscape(htmlLabel)}" style="${style}" vertex="1" parent="1">
          <mxGeometry x="${x}" y="${y}" width="${width}" height="${height}" as="geometry"/>
        </mxCell>`;
}

interface EdgeGeom {
  /** Zusätzliche Wegpunkte (mxPoint) — umleiten um störende Boxen. */
  points?: { x: number; y: number }[];
  /** Extra-Stil-Segmente (Anker, Versatz, Marker). */
  extraStyle?: string;
}

function mxCellEdge(
  id: string,
  source: string,
  target: string,
  label: string,
  geom: EdgeGeom = {},
  dashed = false,
): string {
  // Wegpunkte gehören bei Kanten mit source/target in ein Array as="points" —
  // mxPoint as="sourcePoint" wird nur bei freischwebenden Kanten gelesen.
  const pointsXml = geom.points
    ? `
          <Array as="points">${geom.points.map((p) => `<mxPoint x="${p.x}" y="${p.y}"/>`).join("")}</Array>`
    : "";
  // Logische Referenzen (04 §5, 06 §6 — bewusst kein FK) gestrichelt + grau,
  // damit sie sich von echten FK-Kanten unterscheiden.
  const style = `edgeStyle=orthogonalEdgeStyle;rounded=1;html=1;fontSize=10;labelBackgroundColor=#ffffff;${
    dashed ? "dashed=1;strokeColor=#94a3b8;" : ""
  }${geom.extraStyle ? `${geom.extraStyle};` : ""}`;
  return `        <mxCell id="${id}" value="${xmlEscape(label)}" style="${style}" edge="1" parent="1" source="${source}" target="${target}">
          <mxGeometry relative="1" as="geometry">${pointsXml}
          </mxGeometry>
        </mxCell>`;
}

/** snake_case-FK-Spalten als lesbares Kanten-Label: owner_id → owner. */
function humanizeFkLabel(col: string): string {
  return col.replace(/_id$/, "").replace(/_/g, " ");
}

function compactLabel(table: Table): string {
  return `<b>${table.name}</b><br>${table.label} · ${table.columns.length} fields`;
}

function bigPictureDrawio(): string {
  const nodes: string[] = [];
  const edges: string[] = [];
  const idOf = new Map<string, string>();
  model.tables.forEach((table, i) => {
    idOf.set(table.name, `n${i}`);
  });

  const NODE_W = 220;
  const NODE_H = 70;
  const ROW_H = 110;
  const COL_W = 260;

  // Positionen vorab berechnen — die Kanten-Logik braucht Quelle/Ziel-Koordinaten.
  const pos = new Map<string, { x: number; y: number; catIdx: number; row: number }>();
  const rowsPerCategory = new Map<string, number>();
  model.tables.forEach((table) => {
    const rows = rowsPerCategory.get(table.category) ?? 0;
    rowsPerCategory.set(table.category, rows + 1);
  });
  // Bug 7: Spalten vertikal zentrieren, damit kurze Kategorien nicht oben kleben
  const maxRows = Math.max(...rowsPerCategory.values());
  const rowCounters = new Map<string, number>();
  model.tables.forEach((table, i) => {
    const catIdx = model.categories.findIndex((c) => c.key === table.category);
    const row = rowCounters.get(table.category) ?? 0;
    rowCounters.set(table.category, row + 1);
    const rows = rowsPerCategory.get(table.category) ?? 1;
    const centerOffset = ((maxRows - rows) / 2) * ROW_H;
    const x = catIdx * COL_W + 40;
    const y = row * ROW_H + 60 + centerOffset;
    pos.set(table.name, { x, y, catIdx, row });
    nodes.push(
      mxCellNode(
        idOf.get(table.name) ?? `n${i}`,
        compactLabel(table),
        x,
        y,
        NODE_W,
        NODE_H,
        categoryColor(table.category),
        "#ffffff",
      ),
    );
  });

  // Nur Business-Kanten (siehe isAuditEdge), in Parent→Child-Richtung
  // konsistent zur Mermaid-Ansicht.
  const businessEdges = model.edges.filter((e) => !isAuditEdge(e));

  // Bug 2: Parallele Kanten (gleiches source->target) fächern — jede bekommt
  // einen anderen exitY/entryY-Anker, gleichmäßig über die Box-Höhe verteilt.
  const parallelGroups = new Map<string, number>();
  for (const e of businessEdges) {
    const key = `${e.toTable}->${e.fromTable}`;
    parallelGroups.set(key, (parallelGroups.get(key) ?? 0) + 1);
  }
  const seenInGroup = new Map<string, number>();

  let edgeIndex = 0;
  for (const edge of businessEdges) {
    const sourceId = idOf.get(edge.toTable) ?? "";
    const targetId = idOf.get(edge.fromTable) ?? "";
    const key = `${edge.toTable}->${edge.fromTable}`;
    const groupSize = parallelGroups.get(key) ?? 1;
    const groupIdx = seenInGroup.get(key) ?? 0;
    seenInGroup.set(key, groupIdx + 1);
    const t = groupSize > 1 ? 0.2 + groupIdx * (0.6 / (groupSize - 1)) : -1;

    let extraStyle = "";
    const geom: EdgeGeom = {};

    if (edge.toTable === edge.fromTable) {
      // Bug 3: Selbstreferenz — Anker auf verschiedenen Seiten + Wegpunkt außen
      const p = pos.get(edge.toTable);
      extraStyle = "exitX=1;exitY=0.25;exitDx=0;exitDy=0;entryX=1;entryY=0.75;entryDx=0;entryDy=0";
      if (p) geom.points = [{ x: p.x + NODE_W + 40, y: p.y + 25 }];
    } else {
      const sp = pos.get(edge.toTable);
      const tp = pos.get(edge.fromTable);
      if (sp && tp && sp.catIdx === tp.catIdx && Math.abs(sp.row - tp.row) > 1) {
        // Bug 1: Same-Column-Multi-Hop — Linie durch die Spalte würde fremde
        // Boxen kreuzen; durch die linke Gutter-Zone außen herumführen.
        const gutterX = sp.x - 30;
        geom.points = [
          { x: gutterX, y: sp.y + 35 },
          { x: gutterX, y: tp.y + 35 },
        ];
      }
      if (t >= 0) {
        extraStyle = `exitY=${t.toFixed(2)};entryY=${t.toFixed(2)};exitDx=0;exitDy=0;entryDx=0;entryDy=0`;
      }
    }

    // Bug 5: Kardinalitätsmarker — genau ein Parent, null-oder-mehrere Children
    extraStyle = extraStyle
      ? `${extraStyle};startArrow=ERone;startFill=0;endArrow=ERmany;endFill=0`
      : "startArrow=ERone;startFill=0;endArrow=ERmany;endFill=0";

    edges.push(
      mxCellEdge(
        `e${edgeIndex}`,
        sourceId,
        targetId,
        humanizeFkLabel(edge.fromColumn),
        {
          ...geom,
          extraStyle,
        },
        edge.kind === "logical",
      ),
    );
    edgeIndex += 1;
  }
  return drawioWrap("erd-big-picture", nodes.join("\n"), edges.join("\n"));
}

function categoryDrawio(catKey: string): string {
  const category = model.categories.find((c) => c.key === catKey);
  if (!category) return "";
  const members = new Set(category.tables);
  const included = new Map<string, Table>();
  for (const tableName of category.tables) {
    const table = tablesByName.get(tableName);
    if (table) included.set(tableName, table);
  }
  // Cross-Category-Nachbarn als graue Knoten mit aufnehmen
  for (const edge of model.edges) {
    if (isAuditEdge(edge)) continue;
    const fromInside = members.has(edge.fromTable);
    const toInside = members.has(edge.toTable);
    if (fromInside && toInside) continue;
    if (!fromInside && !toInside) continue;
    for (const tableName of [edge.fromTable, edge.toTable]) {
      if (!members.has(tableName) && !included.has(tableName)) {
        const table = tablesByName.get(tableName);
        if (table) included.set(tableName, table);
      }
    }
  }

  const nodes: string[] = [];
  const edges: string[] = [];
  const idOf = new Map<string, string>();
  // Mitglieder zuerst (gefärbt), dann Nachbarn (grau, gestrichelt)
  const ordered = [...category.tables, ...[...included.keys()].filter((t) => !members.has(t))];
  ordered.forEach((tableName, i) => {
    const table = included.get(tableName);
    if (!table) return;
    idOf.set(tableName, `n${i}`);
    const isMember = members.has(tableName);
    const col = i % 3;
    const row = Math.floor(i / 3);
    nodes.push(
      mxCellNode(
        `n${i}`,
        compactLabel(table),
        col * 260 + 40,
        row * 120 + 60,
        220,
        70,
        isMember ? categoryColor(table.category) : "#f1f5f9",
        isMember ? "#ffffff" : "#475569",
        !isMember,
      ),
    );
  });

  // Bug 2/5: Parallele Kanten fächern + Kardinalitätsmarker, wie im Big Picture
  const catBusinessEdges = model.edges.filter(
    (e) => !isAuditEdge(e) && idOf.has(e.fromTable) && idOf.has(e.toTable),
  );
  const catParallel = new Map<string, number>();
  for (const e of catBusinessEdges) {
    const key = `${e.toTable}->${e.fromTable}`;
    catParallel.set(key, (catParallel.get(key) ?? 0) + 1);
  }
  const catSeen = new Map<string, number>();

  let edgeIndex = 0;
  for (const edge of catBusinessEdges) {
    const key = `${edge.toTable}->${edge.fromTable}`;
    const groupSize = catParallel.get(key) ?? 1;
    const groupIdx = catSeen.get(key) ?? 0;
    catSeen.set(key, groupIdx + 1);
    const t = groupSize > 1 ? 0.2 + groupIdx * (0.6 / (groupSize - 1)) : -1;

    let extraStyle = "";
    const geom: EdgeGeom = {};

    if (edge.toTable === edge.fromTable) {
      // Bug 3: Selbstreferenz — sichtbarer Loop rechts neben der Box
      const selfIdx = ordered.indexOf(edge.toTable);
      const selfTable = included.get(edge.toTable);
      if (selfTable && selfIdx >= 0) {
        const col = selfIdx % 3;
        const row = Math.floor(selfIdx / 3);
        const x = col * 260 + 40;
        const y = row * 120 + 60;
        extraStyle =
          "exitX=1;exitY=0.25;exitDx=0;exitDy=0;entryX=1;entryY=0.75;entryDx=0;entryDy=0";
        geom.points = [{ x: x + 220 + 40, y: y + 25 }];
      }
    } else if (t >= 0) {
      extraStyle = `exitY=${t.toFixed(2)};entryY=${t.toFixed(2)};exitDx=0;exitDy=0;entryDx=0;entryDy=0`;
    }

    extraStyle = extraStyle
      ? `${extraStyle};startArrow=ERone;startFill=0;endArrow=ERmany;endFill=0`
      : "startArrow=ERone;startFill=0;endArrow=ERmany;endFill=0";

    edges.push(
      mxCellEdge(
        `e${edgeIndex}`,
        idOf.get(edge.toTable) ?? "",
        idOf.get(edge.fromTable) ?? "",
        humanizeFkLabel(edge.fromColumn),
        {
          ...geom,
          extraStyle,
        },
        edge.kind === "logical",
      ),
    );
    edgeIndex += 1;
  }
  return drawioWrap(`cat-${catKey}`, nodes.join("\n"), edges.join("\n"));
}

function entityDrawio(name: string): string {
  const table = tablesByName.get(name);
  if (!table) return "";

  const neighbors: Table[] = [];
  const seen = new Set<string>([name]);
  const relEdges: { from: string; to: string; column: string; dashed: boolean }[] = [];
  for (const edge of model.edges) {
    if (edge.fromTable !== name && edge.toTable !== name) continue;
    relEdges.push({
      from: edge.fromTable,
      to: edge.toTable,
      column: edge.fromColumn,
      dashed: edge.kind === "logical",
    });
    for (const tableName of [edge.fromTable, edge.toTable]) {
      if (seen.has(tableName)) continue;
      seen.add(tableName);
      const related = tablesByName.get(tableName);
      if (related) neighbors.push(related);
    }
  }

  const nodes: string[] = [];
  const edges: string[] = [];
  const idOf = new Map<string, string>();
  idOf.set(name, "main");
  neighbors.forEach((nb, i) => {
    idOf.set(nb.name, `nb${i}`);
  });

  // Haupttabelle: alle Felder auflisten (PK markiert)
  const fieldLines = table.columns
    .map((column) => (column.isPrimaryKey ? `PK ${column.name}` : column.name))
    .join("<br>");
  const mainHeight = 40 + table.columns.length * 16;
  nodes.push(
    mxCellNode(
      "main",
      `<b>${table.name}</b><br>${fieldLines}`,
      40,
      40,
      280,
      mainHeight,
      categoryColor(table.category),
      "#ffffff",
    ),
  );

  // Nachbarn: kompakt, grau
  let y = 40;
  for (const nb of neighbors) {
    nodes.push(
      mxCellNode(
        idOf.get(nb.name) ?? "",
        compactLabel(nb),
        480,
        y,
        200,
        70,
        "#f1f5f9",
        "#475569",
        true,
      ),
    );
    y += 120;
  }

  // Bug 2/5: Parallele Kanten fächern + Kardinalitätsmarker wie im Big Picture
  const entParallel = new Map<string, number>();
  for (const e of relEdges) {
    const key = `${e.to}->${e.from}`;
    entParallel.set(key, (entParallel.get(key) ?? 0) + 1);
  }
  const entSeen = new Map<string, number>();

  relEdges.forEach((edge, i) => {
    const key = `${edge.to}->${edge.from}`;
    const groupSize = entParallel.get(key) ?? 1;
    const groupIdx = entSeen.get(key) ?? 0;
    entSeen.set(key, groupIdx + 1);
    const t = groupSize > 1 ? 0.2 + groupIdx * (0.6 / (groupSize - 1)) : -1;

    let extraStyle = "";
    const geom: EdgeGeom = {};

    if (edge.from === edge.to) {
      // Bug 3: Selbstreferenz der Haupttabelle — Loop rechts neben der Feld-Box
      extraStyle = "exitX=1;exitY=0.25;exitDx=0;exitDy=0;entryX=1;entryY=0.75;entryDx=0;entryDy=0";
      geom.points = [{ x: 40 + 280 + 60, y: 40 + 25 }];
    } else if (t >= 0) {
      extraStyle = `exitY=${t.toFixed(2)};entryY=${t.toFixed(2)};exitDx=0;exitDy=0;entryDx=0;entryDy=0`;
    }

    extraStyle = extraStyle
      ? `${extraStyle};startArrow=ERone;startFill=0;endArrow=ERmany;endFill=0`
      : "startArrow=ERone;startFill=0;endArrow=ERmany;endFill=0";

    edges.push(
      mxCellEdge(
        `e${i}`,
        idOf.get(edge.to) ?? "",
        idOf.get(edge.from) ?? "",
        humanizeFkLabel(`${edge.from}.${edge.column}`),
        { ...geom, extraStyle },
        edge.dashed,
      ),
    );
  });

  return drawioWrap(
    `ent-${name.replace(/[^a-zA-Z0-9_-]/g, "_")}`,
    nodes.join("\n"),
    edges.join("\n"),
  );
}

